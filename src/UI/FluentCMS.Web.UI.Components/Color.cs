namespace FluentCMS.Web.UI.Components;

public enum Color
{
    Primary,
    Secondary,
    Success,
    Danger,
    Warning,
    Info,
    Light,
    Dark,
    Body,
    Muted,
    White,
    Black,
    Transparent
}

/*
| Name          | Description                            | Example Classes                                   |
| ------------- | -------------------------------------- | ------------------------------------------------- |
| `primary`     | Main brand color                       | `.text-primary`, `.bg-primary`, `.border-primary` |
| `secondary`   | Secondary accent color                 | `.text-secondary`, `.bg-secondary`                |
| `success`     | Used for success messages              | `.text-success`, `.bg-success`                    |
| `danger`      | Used for errors or destructive actions | `.text-danger`, `.bg-danger`                      |
| `warning`     | For warnings and alerts                | `.text-warning`, `.bg-warning`                    |
| `info`        | For informational messages             | `.text-info`, `.bg-info`                          |
| `light`       | Light gray background / text           | `.text-light`, `.bg-light`                        |
| `dark`        | Dark gray background / text            | `.text-dark`, `.bg-dark`                          |
| `body`        | Default text color                     | `.text-body`, `.bg-body`                          |
| `muted`       | Muted text color                       | `.text-muted`                                     |
| `white`       | White color                            | `.text-white`, `.bg-white`                        |
| `black`       | Black color                            | `.text-black`, `.bg-black`                        |
| `transparent` | Transparent background                 | `.bg-transparent`                                 |
*/
