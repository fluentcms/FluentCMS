using System.Text;
using FluentCMS.Generators.Emit;
using FluentCMS.Generators.Snapshot;
using FluentCMS.Schema;

namespace FluentCMS.Cli.Generate;

// `generate csharp`: a class per content type, component and block type for FluentCMS.Client, which references none of the
// host's types, and the filter and sort builders of the source generator's emitter over the client's field types, so that
// ArticleFields.Title.Contains("x") reads the same in a host and in a client. Every file starts with the schema hash.
internal static class CSharpEmitter
{
    public const string ClientNamespace = "FluentCMS.Client";

    // The base of the block types, whose JSON names the block type in "type".
    public const string BlockBase = "Block";

    private const string Client = "global::" + ClientNamespace + ".";
    private const string Json = "global::System.Text.Json.JsonElement";
    private const string List = "global::System.Collections.Generic.List";
    private const string Property = "global::System.Text.Json.Serialization.JsonPropertyName";

    public static GeneratedCode Emit(ClientSchema schema, string @namespace)
    {
        ArgumentNullException.ThrowIfNull(schema);

        List<GenerateDiagnostic> diagnostics = [];

        // The builders' emitter warns of a field type it does not know by its text, so it gets no field whose type is not
        // a name; such a field has no builder either way.
        var descriptions = SchemaDescriptions.Of(schema.Model, @namespace)
            .Select(type => type with { Fields = type.Fields.Where(field => ClientSchema.IsFieldTypeName(field.FieldType)).ToEquatableArray() });
        var builders = FieldsEmitter.Emit(descriptions, new EmitOptions(ClientNamespace));
        diagnostics.AddRange(builders.Diagnostics.Select(diagnostic => new GenerateDiagnostic(diagnostic.Code, diagnostic.Message)));

        var prefix = @namespace + ".";
        List<GeneratedFile> files = [.. builders.Sources.Select(source => new GeneratedFile(
            source.HintName.StartsWith(prefix, StringComparison.Ordinal) ? source.HintName[prefix.Length..] : source.HintName,
            Stamp(source.Text, schema.Hash)))];

        var reserved = files.Select(file => file.Name[..^".g.cs".Length]).Append(BlockBase);
        var names = new TypeNames(schema.Model, reserved, diagnostics);
        var writer = new Writer(schema, @namespace, names, [.. reserved, .. names.All], diagnostics);

        foreach (var type in schema.Model.ContentTypes.Concat(schema.Model.Components).Concat(schema.Model.Blocks))
        {
            if (names.Of(type) is { } name)
            {
                files.Add(new GeneratedFile(name + ".g.cs", writer.Type(type, name)));
            }
        }

        if (schema.Model.Blocks.Count > 0)
        {
            files.Add(new GeneratedFile(BlockBase + ".g.cs", writer.BlockBaseClass()));
        }

        return new GeneratedCode([.. files.OrderBy(file => file.Name, StringComparer.Ordinal)], diagnostics);
    }

    public const string Marker = "// Generated by fluentcms generate csharp";

    public static string Header(string hash) => $"{Marker} from the schema {hash}. Do not edit.";

    // The emitter's text starts with "// <auto-generated/>", which the compiler reads to treat the file as generated.
    private static string Stamp(string text, string hash)
    {
        var end = text.IndexOf('\n', StringComparison.Ordinal);
        return text[..(end + 1)] + Header(hash) + "\n" + text[(end + 1)..];
    }

    private sealed class Writer(ClientSchema schema, string @namespace, TypeNames names, HashSet<string> classNames, List<GenerateDiagnostic> diagnostics)
    {
        private static readonly string[] EntryMembers = ["Id", "Status", "Locale", "Version", "CreatedAt", "CreatedBy", "UpdatedAt", "UpdatedBy", "PublishedAt", "Fallbacks"];

        // A property with one of these names would hide a member of object.
        private static readonly string[] ObjectMembers = ["Equals", "GetHashCode", "ToString", "GetType", "ReferenceEquals", "MemberwiseClone", "Finalize"];

        public string Type(SchemaType type, string name)
        {
            var code = Start();
            var isEntry = type.Kind is SchemaTypeKind.Collection or SchemaTypeKind.Singleton;
            var fallbacks = type.Localized && isEntry
                ? type.Fields.Where(field => field.Localizable && FieldsEmitter.IsFieldName(field.Name)).ToList()
                : [];
            var fallbacksName = name + "Fallbacks";
            var hasFallbacks = fallbacks.Count > 0 && classNames.Add(fallbacksName);
            if (fallbacks.Count > 0 && !hasFallbacks)
            {
                diagnostics.Add(new(CliErrorCodes.NameNotGenerated, $"The {TypeNames.Label(type.Kind)} '{type.Name}' gets no Fallbacks property, because {fallbacksName} is taken."));
            }

            switch (type.Kind)
            {
                case SchemaTypeKind.Collection or SchemaTypeKind.Singleton:
                    code.Line($"/// <summary>An entry of the {TypeNames.Label(type.Kind)} <c>{type.Name}</c>.</summary>");
                    code.Line($"[{Client}ContentType({Literal(type.Name)})]");
                    code.Line($"public sealed class {name} : {Client}Entry");
                    break;
                case SchemaTypeKind.Component:
                    code.Line($"/// <summary>The component <c>{type.Name}</c>.</summary>");
                    code.Line($"public sealed class {name}");
                    break;
                default:
                    code.Line($"/// <summary>A block of the type <c>{type.Name}</c>.</summary>");
                    code.Line($"public sealed class {name} : {BlockBase}");
                    break;
            }

            code.Open();
            var members = new HashSet<string>(ObjectMembers.Concat(type.Kind switch
            {
                SchemaTypeKind.Block => ["Id"],
                SchemaTypeKind.Component => [],
                _ => EntryMembers,
            }), StringComparer.Ordinal) { name };
            var first = true;
            foreach (var field in type.Fields)
            {
                var member = FieldsEmitter.IsFieldName(field.Name) ? FieldsEmitter.Pascal(field.Name) : null;
                if (member is null || !members.Add(member))
                {
                    diagnostics.Add(new(CliErrorCodes.NameNotGenerated, $"The field '{type.Name}.{field.Name}' gets no property in {name}, because its name gives no identifier or {member} is taken."));
                    continue;
                }

                if (!first)
                {
                    code.Line();
                }

                first = false;
                var traits = FieldTypeText.Traits(field);
                code.Line($"/// <summary>The field <c>{field.Name}</c>{(traits.Length > 0 ? $" ({traits})" : "")}.</summary>");
                code.Line($"[{Property}({Literal(field.Name)})]");
                code.Line($"public {ClrType(type, field)} {member} {{ get; set; }}");
            }

            if (hasFallbacks)
            {
                code.Line();
                code.Line("/// <summary>The locale each localizable field was read from, when the read fell back to another locale.</summary>");
                code.Line($"[{Property}(\"fallbacks\")]");
                code.Line($"public {fallbacksName}? Fallbacks {{ get; set; }}");
            }

            code.Close();

            if (hasFallbacks)
            {
                code.Line();
                code.Line($"/// <summary>The localizable fields of <c>{type.Name}</c>, each with the locale its value was read from.</summary>");
                code.Line($"public sealed class {fallbacksName}");
                code.Open();
                var fallbackMembers = new HashSet<string>(StringComparer.Ordinal) { fallbacksName };
                var firstFallback = true;
                foreach (var field in fallbacks.Where(field => fallbackMembers.Add(FieldsEmitter.Pascal(field.Name))))
                {
                    if (!firstFallback)
                    {
                        code.Line();
                    }

                    firstFallback = false;
                    code.Line($"/// <summary>The locale of <c>{field.Name}</c>.</summary>");
                    code.Line($"[{Property}({Literal(field.Name)})]");
                    code.Line($"public string? {FieldsEmitter.Pascal(field.Name)} {{ get; set; }}");
                }

                code.Close();
            }

            return End(code);
        }

        public string BlockBaseClass()
        {
            var code = Start();
            code.Line("/// <summary>A block of a block list, of the type its JSON names in <c>type</c>; a type this code does not know reads as this class.</summary>");
            code.Line("[global::System.Text.Json.Serialization.JsonPolymorphic(TypeDiscriminatorPropertyName = \"type\", IgnoreUnrecognizedTypeDiscriminators = true)]");
            foreach (var block in schema.Model.Blocks)
            {
                if (names.Of(block) is { } name)
                {
                    code.Line($"[global::System.Text.Json.Serialization.JsonDerivedType(typeof({name}), {Literal(block.Name)})]");
                }
            }

            code.Line($"public class {BlockBase}");
            code.Open();
            code.Line("/// <summary>The id of the block, unique within its top-level field.</summary>");
            code.Line($"[{Property}(\"id\")]");
            code.Line("public string? Id { get; set; }");
            code.Close();
            return End(code);
        }

        private string ClrType(SchemaType owner, SchemaField field)
        {
            string? single = field.FieldType switch
            {
                "text" or "slug" or "email" or "url" or "longText" => "string",
                "richText" or "json" => Json,
                "integer" => "long",
                "decimal" => "decimal",
                "boolean" => "bool",
                "date" => "global::System.DateOnly",
                "dateTime" => "global::System.DateTimeOffset",
                "select" => "string",
                "relation" => $"{Client}Relation<{(field.Relation is { } relation && names.ContentType(relation.Target) is { } target ? target : Client + "Entry")}>",
                "media" => $"{Client}MediaReference",
                "component" => field.Settings.TryGetValue(FieldSettings.Component, out var component) && component is string componentName ? names.Component(componentName) : null,
                "blocks" => BlockBase,
                _ => null,
            };

            if (single is null)
            {
                if (field.FieldType != "component")
                {
                    diagnostics.Add(new(CliErrorCodes.NoGeneratedType, $"The field '{owner.Name}.{field.Name}' is JSON, because {FieldTypeText.Of(field)} has no type in generated code."));
                }

                return Json + "?";
            }

            return field.Multiple || field.FieldType == "blocks" ? $"{List}<{single}>?" : single + "?";
        }

        private Code Start()
        {
            var code = new Code();
            code.Line("// <auto-generated/>");
            code.Line(Header(schema.Hash));
            code.Line("#nullable enable");
            code.Line();
            code.Line($"namespace {@namespace}");
            code.Open();
            return code;
        }

        private static string End(Code code)
        {
            code.Close();
            return code.ToString();
        }
    }

    internal static string Literal(string text) => "\"" + text.Replace("\\", "\\\\", StringComparison.Ordinal).Replace("\"", "\\\"", StringComparison.Ordinal) + "\"";
}

// Lines with an indent of four spaces a level and LF newlines, as the emitter writes them.
internal sealed class Code
{
    private readonly StringBuilder _text = new();
    private int _indent;

    public void Line(string line = "")
    {
        if (line.Length > 0)
        {
            _text.Append(' ', _indent * 4).Append(line);
        }

        _text.Append('\n');
    }

    public void Open(string brace = "{")
    {
        Line(brace);
        _indent++;
    }

    public void Close(string brace = "}")
    {
        _indent--;
        Line(brace);
    }

    public override string ToString() => _text.ToString();
}
