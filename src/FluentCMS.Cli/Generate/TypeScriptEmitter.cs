using System.Globalization;
using System.Text;
using FluentCMS.Generators.Emit;
using FluentCMS.Generators.Snapshot;
using FluentCMS.Schema;

namespace FluentCMS.Cli.Generate;

// `generate typescript`: one ES module over @fluentcms/client with an interface per content type, component and block
// type, the filter and sort builders of each type with the members and operators of the C# builders, and createClient,
// which binds the content types to the client. A blocks field is the union of its block types on "type".
internal static class TypeScriptEmitter
{
    public const string FileName = "fluentcms.ts";
    public const string Package = "@fluentcms/client";

    // The package is imported as a namespace, so no name of the schema can clash with one of its exports.
    private const string Client = "fluentcms.";

    // What a BlocksField has, which a block type's member may not shadow.
    private static readonly string[] BlocksFieldMembers = ["path", "hasBlock", "isNull", "isNotNull", "toString", "constructor"];

    public static GeneratedCode Emit(ClientSchema schema)
    {
        ArgumentNullException.ThrowIfNull(schema);

        // The builders are the C# emitter's, by name: a type has one here when it has one in C#, and their names are
        // reserved first, as in C#, so that a type and a builder never trade names between the two languages.
        var builders = FieldsEmitter.Emit(SchemaDescriptions.Of(schema.Model, ""), EmitOptions.Sdk).Sources
            .Select(source => source.HintName[..^".g.cs".Length])
            .ToHashSet(StringComparer.Ordinal);

        List<GenerateDiagnostic> diagnostics = [];
        var names = new TypeNames(schema.Model, ["schemaHash", "createClient", .. builders], diagnostics);
        return new GeneratedCode([new GeneratedFile(FileName, new Writer(schema, names, builders, diagnostics).Module())], diagnostics);
    }

    public const string Marker = "// Generated by fluentcms generate typescript";

    public static string Header(string hash) => $"{Marker} from the schema {hash}. Do not edit.";

    private sealed class Writer(ClientSchema schema, TypeNames names, HashSet<string> builders, List<GenerateDiagnostic> diagnostics)
    {
        private readonly SchemaModel _model = schema.Model;
        private readonly HashSet<string> _taken = new(["schemaHash", "createClient", .. builders, .. names.All], StringComparer.Ordinal);
        private readonly Code _body = new();
        private readonly Dictionary<SchemaType, string> _builders = [];

        public string Module()
        {
            // The C# builder of a content type is {Name}Fields, of a component {Name}ComponentFields and of a block type
            // {Name}BlockFields, which is the type's name here with Fields after it.
            foreach (var type in _model.ContentTypes.Concat(_model.Components).Concat(_model.Blocks))
            {
                if (names.Of(type) is { } name && builders.Contains(name + "Fields"))
                {
                    _builders[type] = name + "Fields";
                }
            }

            _body.Line($"export const schemaHash = {Literal(schema.Hash)};");

            foreach (var type in _model.ContentTypes.Concat(_model.Components).Concat(_model.Blocks))
            {
                if (names.Of(type) is { } name)
                {
                    _body.Line();
                    Interface(type, name);
                }
            }

            foreach (var type in _model.Components.Concat(_model.Blocks))
            {
                if (BuilderName(type) is { } builder)
                {
                    _body.Line();
                    if (type.Kind == SchemaTypeKind.Component)
                    {
                        ComponentBuilder(type, builder);
                    }
                    else
                    {
                        BlockBuilder(type, builder);
                    }
                }
            }

            foreach (var type in _model.ContentTypes)
            {
                if (BuilderName(type) is { } builder)
                {
                    _body.Line();
                    ContentTypeBuilder(type, builder);
                }
            }

            _body.Line();
            CreateClient();

            var module = new Code();
            module.Line(Header(schema.Hash));
            module.Line($"import * as fluentcms from {Literal(Package)};");
            module.Line();
            return module + _body.ToString();
        }

        private void Interface(SchemaType type, string name)
        {
            var isEntry = type.Kind is SchemaTypeKind.Collection or SchemaTypeKind.Singleton;
            _body.Line($"/** {Describe(type)} */");
            if (isEntry)
            {
                _body.Open($"export interface {name} extends {Client}Entry {{");
            }
            else
            {
                _body.Open($"export interface {name} {{");
            }

            if (type.Kind == SchemaTypeKind.Block)
            {
                _body.Line($"type: {Literal(type.Name)};");
                _body.Line("id?: string;");
            }

            foreach (var field in type.Fields.Where(field => FieldsEmitter.IsFieldName(field.Name)))
            {
                if (FieldTypeText.Traits(field) is { Length: > 0 } traits)
                {
                    _body.Line($"/** {traits} */");
                }

                _body.Line($"{field.Name}?: {ValueType(type, field)} | null;");
            }

            var localizable = type.Localized && isEntry ? type.Fields.Where(field => field.Localizable && FieldsEmitter.IsFieldName(field.Name)).ToList() : [];
            if (localizable.Count > 0)
            {
                _body.Line("/** The locale each localizable field was read from, when the read fell back to another locale. */");
                _body.Line($"fallbacks?: {{ {string.Join(" ", localizable.Select(field => $"{field.Name}?: string;"))} }};");
            }

            _body.Close("}");
        }

        private string ValueType(SchemaType owner, SchemaField field)
        {
            var single = field.FieldType switch
            {
                "text" or "slug" or "email" or "url" or "longText" or "date" or "dateTime" => "string",
                "integer" or "decimal" => "number",
                "boolean" => "boolean",
                "richText" => Import("RichText"),
                "json" => "unknown",
                "select" => Options(field),
                "relation" => field.Relation is { } relation && names.ContentType(relation.Target) is { } target
                    ? $"{Import("Relation")}<{target}, {Literal(relation.Target)}>"
                    : $"{Import("Reference")}",
                "media" => Import("MediaReference"),
                "component" => field.Settings.TryGetValue(FieldSettings.Component, out var component) && component is string componentName ? names.Component(componentName) : null,
                "blocks" => Union(field),
                _ => null,
            };

            if (single is null)
            {
                if (field.FieldType != "component")
                {
                    diagnostics.Add(new(CliErrorCodes.NoGeneratedType, $"The field '{owner.Name}.{field.Name}' is unknown, because {FieldTypeText.Of(field)} has no type in generated code."));
                }

                return "unknown";
            }

            return field.Multiple || field.FieldType == "blocks" ? $"({single})[]" : single;
        }

        private static string Options(SchemaField field) =>
            field.Settings.TryGetValue(FieldSettings.Options, out var options) && options is IEnumerable<string> values && values.Any()
                ? string.Join(" | ", values.Select(Literal))
                : "string";

        private string Union(SchemaField field)
        {
            var blocks = field.Settings.TryGetValue(FieldSettings.Blocks, out var value) && value is IEnumerable<string> list ? list.ToList() : [];
            var types = blocks.Select(names.Block).OfType<string>().ToList();
            return types.Count > 0 ? string.Join(" | ", types) : "never";
        }

        private static string Import(string name) => Client + name;

        private string? BuilderName(SchemaType type) => _builders.GetValueOrDefault(type);

        private void ContentTypeBuilder(SchemaType type, string builder)
        {
            List<(SchemaField Field, string ClassName)> lists = [];
            List<string> members = [];
            foreach (var field in type.Fields.Where(field => FieldsEmitter.IsFieldName(field.Name)))
            {
                if (Member(type, field, path: Literal(field.Name), lists) is { } value)
                {
                    members.Add($"{field.Name}: {value},");
                }
            }

            foreach (var (field, className) in lists)
            {
                BlocksBuilder(field, className);
                _body.Line();
            }

            _body.Line($"/** Typed filters and sorts on the fields of the {TypeNames.Label(type.Kind)} `{type.Name}`. */");
            _body.Open($"export const {builder} = {{");
            foreach (var member in members)
            {
                _body.Line(member);
            }

            _body.Close("} as const;");
        }

        private void ComponentBuilder(SchemaType type, string builder)
        {
            List<(SchemaField Field, string ClassName)> lists = [];
            List<(string Name, string Type, string Value)> members = [];
            foreach (var field in type.Fields.Where(field => FieldsEmitter.IsFieldName(field.Name) && field.Name != "constructor"))
            {
                if (Member(type, field, path: $"this.#path + {Literal("." + field.Name)}", lists) is { } value)
                {
                    members.Add((field.Name, TypeOf(value), value));
                }
            }

            foreach (var (field, className) in lists)
            {
                BlocksBuilder(field, className);
                _body.Line();
            }

            _body.Line($"/** Typed filters and sorts on the fields of the component `{type.Name}`, below the field that holds it. */");
            _body.Open($"export class {builder} {{");
            Constructor();
            foreach (var (name, memberType, value) in members)
            {
                _body.Line();
                _body.Open($"get {name}(): {memberType} {{");
                _body.Line($"return {value};");
                _body.Close();
            }

            _body.Close();
        }

        private void BlockBuilder(SchemaType type, string builder)
        {
            _body.Line($"/** Typed filters on the fields of the block type `{type.Name}` in a block list, one level deep. */");
            _body.Open($"export class {builder} {{");
            Constructor();
            foreach (var field in type.Fields.Where(field => FieldsEmitter.IsFieldName(field.Name) && field.Name != "constructor"))
            {
                if (BlockFieldType(field) is not { } fieldType)
                {
                    continue;
                }

                _body.Line();
                _body.Open($"get {field.Name}(): {Client}{fieldType} {{");
                _body.Line($"return new {Client}{fieldType}(this.#path + {Literal("." + type.Name + "." + field.Name)});");
                _body.Close();
            }

            _body.Close();
        }

        private void BlocksBuilder(SchemaField field, string className)
        {
            _body.Line($"/** The block types of the field `{field.Name}`, and the presence of each in the list. */");
            _body.Open($"export class {className} extends {Client}BlocksField {{");
            var used = new HashSet<string>(BlocksFieldMembers, StringComparer.Ordinal);
            var first = true;
            foreach (var block in field.Settings.TryGetValue(FieldSettings.Blocks, out var value) && value is IEnumerable<string> list ? list : [])
            {
                if (!FieldsEmitter.IsTypeName(block))
                {
                    continue;
                }

                var pascal = FieldsEmitter.Pascal(block);
                var member = char.ToLowerInvariant(pascal[0]) + pascal[1..];
                var has = "has" + pascal;
                var builder = _model.FindBlock(block) is { } type ? BuilderName(type) : null;
                if (builder is not null ? !used.Add(member) || !used.Add(has) : !used.Add(has))
                {
                    continue;
                }

                if (!first)
                {
                    _body.Line();
                }

                first = false;
                if (builder is not null)
                {
                    _body.Open($"get {member}(): {builder} {{");
                    _body.Line($"return new {builder}(this.path);");
                    _body.Close();
                    _body.Line();
                }

                _body.Open($"{has}(): {Client}FieldFilter {{");
                _body.Line($"return this.hasBlock({Literal(block)});");
                _body.Close();
            }

            _body.Close();
        }

        // The builder of a field at a path, or null for one the C# emitter gives none: a repeated component, a component
        // without a builder, a field type without one.
        private string? Member(SchemaType owner, SchemaField field, string path, List<(SchemaField Field, string ClassName)> lists)
        {
            switch (field.FieldType)
            {
                case "blocks":
                    var className = $"{names.Of(owner)}{FieldsEmitter.Pascal(field.Name)}Blocks";
                    if (!_taken.Add(className))
                    {
                        diagnostics.Add(new(CliErrorCodes.NameNotGenerated, $"The field '{owner.Name}.{field.Name}' gets no builder, because {className} is taken."));
                        return null;
                    }

                    lists.Add((field, className));
                    return $"new {className}({path})";
                case "component" when field.Multiple:
                    return null;
                case "component":
                    return field.Settings.TryGetValue(FieldSettings.Component, out var component) && component is string name && _model.FindComponent(name) is { } type && BuilderName(type) is { } builder
                        ? $"new {builder}({path})"
                        : null;
                default:
                    if (FieldType(field) is not { } fieldType)
                    {
                        return null;
                    }

                    return $"new {Client}{fieldType}({path})";
            }
        }

        private static string TypeOf(string construction) => construction[4..construction.IndexOf('(', StringComparison.Ordinal)];

        private void Constructor()
        {
            _body.Line("readonly #path: string;");
            _body.Line();
            _body.Open("constructor(path: string) {");
            _body.Line("this.#path = path;");
            _body.Close();
        }

        private void CreateClient()
        {
            _body.Line("/** The content types of this schema on a client of @fluentcms/client. */");
            _body.Open($"export function createClient(options: {Client}ClientOptions | {Client}FluentCmsClient) {{");
            _body.Line($"const client = options instanceof {Client}FluentCmsClient ? options : new {Client}FluentCmsClient(options);");
            _body.Open("return {");
            foreach (var type in _model.ContentTypes)
            {
                if (names.Of(type) is { } name)
                {
                    var key = char.ToLowerInvariant(name[0]) + name[1..];
                    var kind = type.Kind == SchemaTypeKind.Singleton ? "singleton" : "collection";
                    _body.Line($"{key}: client.{kind}<{name}>({Literal(type.Name)}),");
                }
            }

            _body.Close("};");
            _body.Close();
        }

        private static string? FieldType(SchemaField field) => field.FieldType switch
        {
            "text" or "slug" or "email" or "url" => "TextField",
            "longText" => "LongTextField",
            "richText" => "RichTextField",
            "integer" or "decimal" => "NumberField",
            "boolean" => "BooleanField",
            "date" or "dateTime" => "DateField",
            "select" => field.Multiple ? "SelectListField" : "SelectField",
            "json" => "JsonField",
            "relation" => "RelationField",
            "media" => "MediaField",
            _ => null,
        };

        private static string? BlockFieldType(SchemaField field) => field.FieldType switch
        {
            "text" or "slug" or "email" or "url" => "BlockTextField",
            "select" => field.Multiple ? "BlockContainsField" : "BlockTextField",
            "longText" => "BlockContainsField",
            "integer" or "decimal" or "boolean" or "date" or "dateTime" => "BlockValueField",
            _ => null,
        };

        private static string Describe(SchemaType type) => type.Kind switch
        {
            SchemaTypeKind.Collection or SchemaTypeKind.Singleton => $"An entry of the {TypeNames.Label(type.Kind)} `{type.Name}`.",
            SchemaTypeKind.Component => $"The component `{type.Name}`.",
            _ => $"A block of the type `{type.Name}`.",
        };
    }

    // A JSON string, which is also a TypeScript string literal.
    internal static string Literal(string text)
    {
        var builder = new StringBuilder("\"");
        foreach (var character in text)
        {
            builder.Append(character switch
            {
                '"' => "\\\"",
                '\\' => "\\\\",
                '\n' => "\\n",
                '\r' => "\\r",
                '\t' => "\\t",
                '\u2028' => "\\u2028",
                '\u2029' => "\\u2029",
                < ' ' => "\\u" + ((int)character).ToString("x4", CultureInfo.InvariantCulture),
                _ => character.ToString(),
            });
        }

        return builder.Append('"').ToString();
    }
}
