using FluentCMS.Core.Storage;
using FluentCMS.Core.Tests.Schema;
using FluentCMS.Data.PostgreSql;
using FluentCMS.Data.Sqlite;
using FluentCMS.Data.SqlServer;
using FluentCMS.Data.Tests.Sqlite;
using FluentCMS.Schema;
using Microsoft.EntityFrameworkCore;
using Shouldly;
using Xunit;

namespace FluentCMS.Data.Tests.Migrations;

public sealed class ContentMigrationGeneratorTests : IDisposable
{
    private readonly SqliteFileDatabase _database = new();

    private static CancellationToken Token => TestContext.Current.CancellationToken;

    public void Dispose() => _database.Dispose();

    [Fact]
    public void TheMigrationIsMarkedAutoGenerated()
    {
        var migration = GeneratedMigrations.Scaffold(ArticleSchemas.Titled, "Initial");

        migration.MigrationCode.ShouldStartWith("// <auto-generated />");
        migration.MetadataCode.ShouldStartWith("// <auto-generated />");
        migration.SnapshotCode.ShouldStartWith("// <auto-generated />");
    }

    [Fact]
    public void TheContentStreamLeavesOutSystemTablesAndJsonFunctions()
    {
        var schema = SampleSchema.FromClasses().Build();

        var migration = GeneratedMigrations.Scaffold(schema, "Initial");

        migration.MigrationCode.ShouldContain("name: \"cms_article\"");
        migration.MigrationCode.ShouldContain("name: \"cms_article_i18n\"");
        migration.MigrationCode.ShouldNotContain("cms_document");
        migration.MigrationCode.ShouldNotContain("cms_reference");
        migration.MigrationCode.ShouldNotContain("cms_version");
        migration.MigrationCode.ShouldNotContain("json_each");
        migration.MigrationCode.ShouldNotContain("SqliteJson");
    }

    [Fact]
    public void TheContentStreamCarriesNoSystemSeedData()
    {
        var first = GeneratedMigrations.Scaffold(ArticleSchemas.Titled, "Initial");

        first.MigrationCode.ShouldNotContain("InsertData");
        first.MigrationCode.ShouldNotContain("cms_role");

        var second = GeneratedMigrations.Scaffold(ArticleSchemas.WithSubtitle, "AddSubtitle", GeneratedMigrations.CompileFirst(ArticleSchemas.Titled));

        second.MigrationCode.ShouldNotContain("InsertData");
        second.MigrationCode.ShouldNotContain("cms_role");
    }

    [Fact]
    public void ASecondGenerationScaffoldsOnlyTheChangeEvenAfterAPendingChangesCheck()
    {
        var migrations = GeneratedMigrations.CompileFirst(ArticleSchemas.Titled);

        using (var checking = ContentMigrations.CreateContext(new SqliteDataProvider("Data Source=:memory:"), ArticleSchemas.WithSubtitle, migrations))
        {
            checking.Database.HasPendingModelChanges().ShouldBeTrue();
        }

        var second = GeneratedMigrations.Scaffold(ArticleSchemas.WithSubtitle, "AddSubtitle", migrations);

        second.MigrationCode.ShouldContain("migrationBuilder.AddColumn<string>");
        second.MigrationCode.ShouldContain("name: \"subtitle\"");
        second.MigrationCode.ShouldNotContain("CreateTable");
    }

    [Fact]
    public async Task AGeneratedMigrationOfTheSampleSchemaCompilesAndApplies()
    {
        var schema = SampleSchema.FromClasses().Build();
        using var host = _database.CreateHost(schema, "Production", GeneratedMigrations.CompileFirst(schema));

        await host.StartAsync(Token);

        _database.Tables().ShouldContain("cms_article_i18n");
    }

    [Fact]
    public void ItGeneratesForPostgreSql()
    {
        var migration = ContentMigrationGenerator.Scaffold(
            () => ContentMigrations.CreateContext(new PostgreSqlDataProvider("Host=localhost;Database=never_opened"), ArticleSchemas.Titled, typeof(CmsDbContext).Assembly),
            "Initial",
            GeneratedMigrations.Namespace);

        migration.MigrationCode.ShouldContain("name: \"cms_article\"");
        migration.MigrationCode.ShouldContain("type: \"uuid\"");
        migration.MigrationCode.ShouldNotContain("cms_document");
    }

    [Fact]
    public void ItGeneratesForSqlServer()
    {
        var migration = ContentMigrationGenerator.Scaffold(
            () => ContentMigrations.CreateContext(new SqlServerDataProvider("Server=localhost;Database=never_opened"), ArticleSchemas.Titled, typeof(CmsDbContext).Assembly),
            "Initial",
            GeneratedMigrations.Namespace);

        migration.MigrationCode.ShouldContain("name: \"cms_article\"");
        migration.MigrationCode.ShouldContain("type: \"uniqueidentifier\"");
        migration.MigrationCode.ShouldNotContain("cms_document");
    }
}
