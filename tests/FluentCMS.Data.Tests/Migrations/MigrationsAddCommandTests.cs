    [Fact]
    public async Task ItGeneratesAContentMigrationThatCompilesAndApplies()
    {
        (await Add("Initial", ArticleSchemas.Titled)).ShouldBe(0, _error.ToString());

        var files = GeneratedFiles().Select(Path.GetFileName).ToList();
        files.Count.ShouldBe(3);
        files.ShouldContain("CmsDbContextModelSnapshot.cs");
        files.ShouldContain(file => file!.EndsWith("_Initial.cs", StringComparison.Ordinal));
        files.ShouldContain(file => file!.EndsWith("_Initial.Designer.cs", StringComparison.Ordinal));

        File.ReadAllText(GeneratedFiles().Single(file => file.EndsWith("_Initial.cs", StringComparison.Ordinal))).ShouldStartWith("// <auto-generated />");
        _output.ToString().ShouldContain("CmsDbContextModelSnapshot.cs");

        using var host = _database.CreateHost(ArticleSchemas.Titled, "Production", CompileGeneratedFiles());
        await host.StartAsync(Token);

        _database.Tables().ShouldContain("cms_article");
        _database.ReadStrings("select \"MigrationId\" from cms_content__migrations").ShouldHaveSingleItem().ShouldEndWith("_Initial");
    }

    [Fact]
    public async Task ASecondMigrationAddsTheFieldAndKeepsOneSnapshot()
    {
