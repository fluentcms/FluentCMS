using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Testing;
using Microsoft.CodeAnalysis.Testing;
using Microsoft.CodeAnalysis.Text;
using Shouldly;
using Xunit;

namespace FluentCMS.Generators.Tests;

public sealed class GeneratorTests
{
    private const string Product = """
        using System.Collections.Generic;
        using FluentCMS.Schema;

        namespace Shop;

        [Collection("product")]
        public sealed class Product : ContentItem
        {
            [Text, Required]
            public string Title { get; set; } = "";

            [Integer]
            public int Stock { get; set; }

            [Component]
            public Size Size { get; set; } = new();

            public string NotAField { get; set; } = "";
        }

        [Component]
        public sealed class Size
        {
            [Decimal]
            public decimal Width { get; set; }
        }
        """;

    private const string ProductFields = """
        // <auto-generated/>
        #nullable enable

        namespace Shop
        {
            /// <summary>Typed filters and sorts on the fields of the collection <c>product</c>.</summary>
            public static class ProductFields
            {
                /// <summary>The field <c>title</c> (text).</summary>
                public static global::FluentCMS.Content.TextField Title { get; } = new global::FluentCMS.Content.TextField("title");

                /// <summary>The field <c>stock</c> (integer).</summary>
                public static global::FluentCMS.Content.NumberField<long> Stock { get; } = new global::FluentCMS.Content.NumberField<long>("stock");

                /// <summary>The field <c>size</c> (component).</summary>
                public static global::Shop.SizeComponentFields Size { get; } = new global::Shop.SizeComponentFields("size");
            }
        }

        """;

    private const string SizeFields = """
        // <auto-generated/>
        #nullable enable

        namespace Shop
        {
            /// <summary>Typed filters and sorts on the fields of the component <c>size</c>, below the field that holds it.</summary>
            public sealed class SizeComponentFields
            {
                private readonly string _path;

                /// <summary>Creates the builder for a field that holds the component.</summary>
                /// <param name="path">The path of the field.</param>
                public SizeComponentFields(string path)
                {
                    _path = path;
                }

                /// <summary>The field <c>width</c> (decimal).</summary>
                public global::FluentCMS.Content.NumberField<decimal> Width => new global::FluentCMS.Content.NumberField<decimal>(_path + ".width");
            }
        }

        """;

    [Fact]
    public async Task TheBuildersOfGivenSourcesAreEmitted()
    {
        var test = new CSharpSourceGeneratorTest<FieldsGenerator, DefaultVerifier>
        {
            ReferenceAssemblies = new ReferenceAssemblies("net10.0"),
            TestState =
            {
                Sources = { ("Product.cs", Product) },
                GeneratedSources =
                {
                    (typeof(FieldsGenerator), "Shop.ProductFields.g.cs", SourceText.From(ProductFields.ReplaceLineEndings("\n"), Encoding.UTF8)),
                    (typeof(FieldsGenerator), "Shop.SizeComponentFields.g.cs", SourceText.From(SizeFields.ReplaceLineEndings("\n"), Encoding.UTF8)),
                },
            },
        };
        test.TestState.AdditionalReferences.AddRange(Generation.References);

        await test.RunAsync(TestContext.Current.CancellationToken);
    }

    [Fact]
    public void RenamingAPropertyBreaksTheBuildAtEveryUseOfItsBuilder()
    {
        const string uses = """
            using FluentCMS.Content;

            namespace Shop;

            public static class Queries
            {
                public static FieldFilter Named(string text) => ProductFields.Title.Contains(text);

                public static SortField ByTitle() => ProductFields.Title.Ascending();

                public static FieldFilter Wide() => ProductFields.Size.Width.Gt(10m);
            }
            """;

        Generation.Errors(Generation.Compile(("Product.cs", Product), ("Queries.cs", uses))).ShouldBeEmpty();

        var renamed = Product.Replace("public string Title", "public string Headline", StringComparison.Ordinal);
        var errors = Generation.Errors(Generation.Compile(("Product.cs", renamed), ("Queries.cs", uses)));

        errors.Select(error => (error.Id, error.Location.SourceTree?.FilePath, error.Location.GetLineSpan().StartLinePosition.Line))
            .ShouldBe([("CS0117", "Queries.cs", 6), ("CS0117", "Queries.cs", 8)], ignoreOrder: true);
    }

    [Fact]
    public void AnEditThatTouchesNoContentTypeGeneratesNothingAgain()
    {
        var other = Generation.Parse("namespace Shop; public static class Other { public static int Value => 1; }", "Other.cs");
        var compilation = Generation.Compile(("Product.cs", Product)).AddSyntaxTrees(other);
        var driver = Generation.Driver().RunGenerators(compilation, TestContext.Current.CancellationToken);

        var edited = compilation.ReplaceSyntaxTree(other, Generation.Parse("namespace Shop; public static class Other { public static int Value => 2; }", "Other.cs"));
        var result = driver.RunGenerators(edited, TestContext.Current.CancellationToken).GetRunResult().Results.Single();

        Reasons(result, FieldsGenerator.TypesStep).ShouldAllBe(reason => reason == IncrementalStepRunReason.Cached || reason == IncrementalStepRunReason.Unchanged);
        Reasons(result, FieldsGenerator.EmitStep).ShouldAllBe(reason => reason == IncrementalStepRunReason.Cached || reason == IncrementalStepRunReason.Unchanged);
        result.TrackedOutputSteps.SelectMany(step => step.Value).SelectMany(run => run.Outputs).Select(output => output.Reason)
            .ShouldAllBe(reason => reason == IncrementalStepRunReason.Cached || reason == IncrementalStepRunReason.Unchanged);
    }

    [Fact]
    public void AnEditOfAContentTypeGeneratesAgain()
    {
        var compilation = Generation.Compile(("Product.cs", Product));
        var driver = Generation.Driver().RunGenerators(compilation, TestContext.Current.CancellationToken);

        var tree = compilation.SyntaxTrees.Single();
        var edited = compilation.ReplaceSyntaxTree(tree, Generation.Parse(Product.Replace("[Integer]", "[Decimal]", StringComparison.Ordinal), "Product.cs"));
        var result = driver.RunGenerators(edited, TestContext.Current.CancellationToken).GetRunResult().Results.Single();

        Reasons(result, FieldsGenerator.EmitStep).ShouldContain(IncrementalStepRunReason.Modified);
        Generation.Generated(result, "Shop.ProductFields.g.cs").ShouldContain("NumberField<decimal> Stock");
    }

    [Fact]
    public void AFieldAttributeTheGeneratorDoesNotKnowIsReported()
    {
        const string source = """
            using FluentCMS.Schema;

            namespace Shop;

            public sealed class GeoAttribute() : FieldAttribute("geo");

            [Collection("store")]
            public sealed class Store : ContentItem
            {
                [Text]
                public string Name { get; set; } = "";

                [Geo]
                public string? Location { get; set; }
            }
            """;

        var result = Generation.Run(Generation.Compile(("Store.cs", source)));

        var diagnostic = result.Diagnostics.ShouldHaveSingleItem();
        diagnostic.Id.ShouldBe("FCMS0101");
        diagnostic.Severity.ShouldBe(DiagnosticSeverity.Info);
        diagnostic.GetMessage(System.Globalization.CultureInfo.InvariantCulture).ShouldContain("[GeoAttribute]");
        diagnostic.Location.GetLineSpan().StartLinePosition.Line.ShouldBe(13);
        Generation.Generated(result, "Shop.StoreFields.g.cs").ShouldNotContain("Location");
    }

    [Fact]
    public void AMemberNameTakenInTheBuilderIsReportedAtTheField()
    {
        const string source = """
            using FluentCMS.Schema;

            namespace Shop;

            [Collection("page")]
            public sealed class Page : ContentItem
            {
                [Blocks(typeof(Banner))]
                public BlockList Body { get; set; } = [];

                [Text]
                public string? BodyBlocks { get; set; }
            }

            [Block("banner")]
            public sealed class Banner
            {
                [Text]
                public string? Heading { get; set; }
            }
            """;

        var result = Generation.Run(Generation.Compile(("Page.cs", source)));

        var diagnostic = result.Diagnostics.ShouldHaveSingleItem();
        diagnostic.Id.ShouldBe("FCMS0102");
        diagnostic.Severity.ShouldBe(DiagnosticSeverity.Warning);
        diagnostic.Location.GetLineSpan().StartLinePosition.Line.ShouldBe(11);
        Generation.Errors(Generation.Compile(("Page.cs", source))).ShouldBeEmpty();
    }

    [Fact]
    public void AComponentDeclaredInAnotherProjectIsReportedAndLeftOut()
    {
        const string library = """
            using FluentCMS.Schema;

            namespace Shared;

            [Component("address")]
            public sealed class Address
            {
                [Text]
                public string? City { get; set; }
            }
            """;

        const string source = """
            using FluentCMS.Schema;

            namespace Shop;

            [Collection("store")]
            public sealed class Store : ContentItem
            {
                [Text]
                public string? Name { get; set; }

                [Component]
                public Shared.Address Address { get; set; } = new();
            }
            """;

        var shared = Generation.Compile(("Address.cs", library));
        using var image = new MemoryStream();
        shared.Emit(image, cancellationToken: TestContext.Current.CancellationToken).Success.ShouldBeTrue();
        var compilation = Generation.Compile(("Store.cs", source)).AddReferences(MetadataReference.CreateFromImage(image.ToArray()));

        var result = Generation.Run(compilation);

        var diagnostic = result.Diagnostics.ShouldHaveSingleItem();
        diagnostic.Id.ShouldBe("FCMS0103");
        diagnostic.Severity.ShouldBe(DiagnosticSeverity.Info);
        diagnostic.Location.GetLineSpan().StartLinePosition.Line.ShouldBe(11);
        Generation.Generated(result, "Shop.StoreFields.g.cs").ShouldNotContain("Address");
        Generation.Errors(compilation).ShouldBeEmpty();
    }

    [Fact]
    public void ATypeWhoseBuilderNameIsTakenIsReportedAtItsOwnClass()
    {
        const string source = """
            using FluentCMS.Schema;

            namespace A
            {
                [Collection("post")]
                public sealed class Post : ContentItem
                {
                }
            }

            namespace B
            {
                [Collection("post")]
                public sealed class Article : ContentItem
                {
                }
            }
            """;

        var result = Generation.Run(Generation.Compile(("Post.cs", source)));

        result.GeneratedSources.Select(generated => generated.HintName).ShouldBe(["A.PostFields.g.cs"]);
        var diagnostic = result.Diagnostics.ShouldHaveSingleItem();
        diagnostic.Id.ShouldBe("FCMS0100");
        diagnostic.Location.GetLineSpan().StartLinePosition.Line.ShouldBe(13);
    }

    [Fact]
    public void AClassTheAttributeReaderRefusesGetsNoBuilder()
    {
        const string source = """
            using FluentCMS.Schema;

            namespace Shop;

            [Collection("loose")]
            public sealed class Loose
            {
                [Text]
                public string? Name { get; set; }
            }

            [Collection("both"), Component]
            public sealed class Both : ContentItem
            {
                [Text]
                public string? Name { get; set; }
            }

            [Collection("open")]
            public abstract class Open : ContentItem
            {
                [Text]
                public string? Name { get; set; }
            }
            """;

        var result = Generation.Run(Generation.Compile(("Shop.cs", source)));

        result.GeneratedSources.ShouldBeEmpty();
        result.Diagnostics.ShouldBeEmpty();
    }

    [Fact]
    public void InheritedFieldsComeFirstAndTheNamesFollowTheAttributeReader()
    {
        const string source = """
            using FluentCMS.Schema;

            namespace Shop;

            public abstract class Listing : ContentItem
            {
                [Text]
                public string? URLSlug { get; set; }
            }

            [Collection]
            public sealed class FAQPage : Listing
            {
                [LongText]
                public string? Answer { get; set; }
            }
            """;

        var text = Generation.Generated(Generation.Run(Generation.Compile(("Shop.cs", source))), "Shop.FaqPageFields.g.cs");

        text.ShouldContain("the collection <c>faq-page</c>");
        text.IndexOf("TextField UrlSlug { get; } = new global::FluentCMS.Content.TextField(\"urlSlug\")", StringComparison.Ordinal)
            .ShouldBeLessThan(text.IndexOf("LongTextField Answer", StringComparison.Ordinal));
    }

    private static IEnumerable<IncrementalStepRunReason> Reasons(GeneratorRunResult result, string step) =>
        result.TrackedSteps[step].SelectMany(run => run.Outputs).Select(output => output.Reason);
}
